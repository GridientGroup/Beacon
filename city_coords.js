window.normalizeCity = function (c) {
  if (!c) return '';
  var out = String(c).trim().replace(/[,.]+$/, '').replace(/\s+/g, ' ');
  // Title-case: "DISTRICT HEIGHTS" → "District Heights"
  out = out.split(' ').map(function (w) {
    return w.charAt(0).toUpperCase() + w.slice(1).toLowerCase();
  }).join(' ');
  return out;
};

window.geocodeCityState = function (city, state) {
  var c = window.normalizeCity(city);
  var s = String(state || '').trim().toUpperCase();
  var key = c + '|' + s;
  if (window.TYPO_MAP && window.TYPO_MAP[key]) key = window.TYPO_MAP[key];
  var coords = window.CITY_COORDS && window.CITY_COORDS[key];
  if (!coords) coords = window.STATE_CENTERS && window.STATE_CENTERS[s];
  if (coords) {
    return {
      lat: coords[0],
      lng: coords[1],
      approximate: !(window.CITY_COORDS && window.CITY_COORDS[key]),
    };
  }
  // Geographic center of the contiguous US — last-resort fallback
  return { lat: 39.0, lng: -98.0, approximate: true };
};
